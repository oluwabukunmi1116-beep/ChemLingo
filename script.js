const classSelect = document.querySelector("#class-select");
const subjectSelect = document.querySelector("#subject-select");
const searchInput = document.querySelector("#topic-search");
const topicsGrid = document.querySelector("#topics-grid");
const topicCount = document.querySelector("#topic-count");
const emptyState = document.querySelector("#empty-state");
const questionsList = document.querySelector("#questions-list");
const practiceTotal = document.querySelector("#practice-total");
const termTabs = [...document.querySelectorAll(".term-tab")];
let activeTerm = "first";

function renderPracticeQuestions() {
  const subject = subjectSelect.value;
  const questions = practiceQuestions[subject];

  practiceTotal.textContent = `${questions.length} questions`;
  questionsList.innerHTML = questions.map(([question, answer], index) => `
    <details class="question-item">
      <summary>
        <span class="question-number">${String(index + 1).padStart(2, "0")}</span>
        <span class="question-text">${question}</span>
        <span class="question-toggle" aria-hidden="true"></span>
      </summary>
      <p class="question-answer"><strong>Answer:</strong> ${answer}</p>
    </details>
  `).join("");
}

function renderTopics() {
  const className = classSelect.value;
  const subject = subjectSelect.value;
  const query = searchInput.value.trim().toLocaleLowerCase();
  const topics = syllabus[className][subject][activeTerm];
  const filteredTopics = topics.filter(([title, description]) =>
    `${title} ${description}`.toLocaleLowerCase().includes(query)
  );

  topicsGrid.innerHTML = filteredTopics.map(([title, description], index) => `
    <article class="topic-card">
      <span class="topic-number">${String(index + 1).padStart(2, "0")}</span>
      <div>
        <h2>${title}</h2>
        <p>${description}</p>
      </div>
    </article>
  `).join("");
  topicCount.textContent = `${filteredTopics.length} ${filteredTopics.length === 1 ? "topic" : "topics"}`;
  emptyState.hidden = filteredTopics.length > 0;
  topicsGrid.hidden = filteredTopics.length === 0;
}

classSelect.addEventListener("change", renderTopics);
subjectSelect.addEventListener("change", () => {
  renderTopics();
  renderPracticeQuestions();
});
searchInput.addEventListener("input", renderTopics);

termTabs.forEach((tab) => {
  tab.addEventListener("click", () => {
    activeTerm = tab.dataset.term;
    termTabs.forEach((item) => {
      const isActive = item === tab;
      item.classList.toggle("is-active", isActive);
      item.setAttribute("aria-selected", String(isActive));
    });
    renderTopics();
  });
});

document.addEventListener("keydown", (event) => {
  if ((event.ctrlKey || event.metaKey) && event.key.toLowerCase() === "k") {
    event.preventDefault();
    searchInput.focus();
  }
});

renderTopics();
renderPracticeQuestions();